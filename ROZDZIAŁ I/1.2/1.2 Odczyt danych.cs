// ReadLine – pobiera cały tekst
Console.Write("Wpisz swoje miasto: ");
string miasto = Console.ReadLine(); // np. "Warszawa"
Console.WriteLine(miasto);

// Read – pobiera kod pierwszego wpisanego znaku
Console.Write("Wpisz jedną literę: ");
int kodZnaku = Console.Read(); // jeśli wpiszesz "A", zmienna otrzyma wartość 65
Console.WriteLine(kodZnaku);

