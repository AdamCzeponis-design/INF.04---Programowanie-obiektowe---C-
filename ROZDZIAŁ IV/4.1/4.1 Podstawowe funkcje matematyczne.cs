
        double liczbaUjemna = -15.5;
        double kwadrat = 9.0;

        // Wartość bezwzględna
        double bezwzgledna = Math.Abs(liczbaUjemna);
        Console.WriteLine($"Wartość bezwzględna z {liczbaUjemna} to: {bezwzgledna}");

        // Pierwiastek kwadratowy
        double pierwiastek = Math.Sqrt(kwadrat);
        Console.WriteLine($"Pierwiastek kwadratowy z {kwadrat} to: {pierwiastek}");

        // Potęgowanie (2 do potęgi 4)
        double potega = Math.Pow(2, 4);
        Console.WriteLine($"2 do potęgi 4 wynosi: {potega}");



